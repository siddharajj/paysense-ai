export const COUNTRY_LIST = Object.values(COUNTRIES);

export function convertCurrency(amount, fromCode, toCode, customRates = {}) {
  const from = COUNTRIES[fromCode];
  const to = COUNTRIES[toCode];
  if (!from || !to || fromCode === toCode) return amount;
  const fromUsd = customRates[fromCode] ?? from.usdRate;
  const toUsd = customRates[toCode] ?? to.usdRate;
  return (amount * fromUsd) / toUsd;
}
